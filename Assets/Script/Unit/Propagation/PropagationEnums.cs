// 14장: 전투 관련 소리 4종(공격 실행음/피격 발생 공격음/피격 비명/사망음) + 이동음 + 함정 작동음.
public enum SoundType
{
	Movement,        // 이동음
	AttackExecution, // 공격 실행음
	HitImpact,       // 피격 발생 공격음
	HitScream,       // 피격 비명 (최종 HP 감소량 ≥ 최대 HP × 10%)
	Death,           // 사망음
	TrapActivation,  // 함정 작동음
}

// 17장: 공격 형태에 따라 방향 정보를 얻을 수 있는지가 갈린다. 근접=공격원 방향, 투사체/원거리/투사체
// 마법=진행 방향, 광역·지면 영역 공격은 방향을 특정할 수 없어 정보 자체가 생성되지 않는다.
public enum AttackShape
{
	Melee,      // 근접 — 공격원 방향
	Projectile, // 투사체·원거리·투사체 마법 — 진행 방향
	AreaGround, // 광역·지면 영역 — 방향 정보 없음
}
